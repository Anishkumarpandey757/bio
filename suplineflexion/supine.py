    cap = cv2.VideoCapture(video_path)
    n   = int(cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0)

    # choose index by kinematic column, fallback to middle
    idx = _safe_argmax(df[select_col].to_numpy()) if (select_col in df.columns) else None
    if idx is None: idx = n//2

    # find a nearby frame that actually returns landmarks
    i_found, frame, lms = _nearest_frame_with_landmarks(cap, idx, max_jump=20, model_complexity=model_complexity)
    cap.release()
    if frame is None:
        print("Could not find a frame with landmarks near", idx)
        return

    H, W = frame.shape[:2]

    # draw skeleton (use default styles but make lines thicker for visibility)
    mp_drawing.draw_landmarks(
        image=frame,
        landmark_list=lms,                         # <-- just pass lms directly
        connections=mp_pose.POSE_CONNECTIONS,
        landmark_drawing_spec=mp_drawing.DrawingSpec(thickness=thick, circle_radius=rad),
        connection_drawing_spec=mp_drawing.DrawingSpec(thickness=thick)
    )

    # add explicit white dots + labels so points are obvious
    for j, lm in enumerate(lms.landmark):
        if not (0.0 <= lm.x <= 1.0 and 0.0 <= lm.y <= 1.0):
            continue
        x, y = int(lm.x * W), int(lm.y * H)
        # outline + fill for any background
        cv2.circle(frame, (x, y), rad+2, (0, 0, 0), -1)
        cv2.circle(frame, (x, y), rad,   (255, 255, 255), -1)
        if label_all or (j in LM_INV):
            label = LM_INV.get(j, str(j))
            cv2.putText(frame, label, (x+6, y-6), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (0,0,0), 3, cv2.LINE_AA)
            cv2.putText(frame, label, (x+6, y-6), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (255,255,255), 1, cv2.LINE_AA)

    # header banner
    cv2.rectangle(frame, (10,10), (410, 50), (0,0,0), -1)
    cv2.putText(frame, f"Best frame: {i_found} (by {select_col})",
                (20,40), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255,255,255), 2, cv2.LINE_AA)

    cv2.imwrite(out_png, frame)

