def angle_3pt(A, B, C, eps=1e-8):
    BA, BC = A - B, C - B
    na, nc = np.linalg.norm(BA), np.linalg.norm(BC)
    if na < eps or nc < eps: return np.nan
    cosv = np.dot(BA, BC) / (na*nc)
    return float(np.degrees(np.arccos(np.clip(cosv, -1.0, 1.0))))

def angle_to_vertical(P0, P1):
    v = P1 - P0
    n = np.linalg.norm(v)
    if n < 1e-8: return np.nan
    v = v / n
    # image coords: +y is down, so "up" vector is (0, -1)
    return float(np.degrees(np.arccos(np.clip(np.dot(v, np.array([0.0, -1.0])), -1, 1))))

def angle_between(u, v, eps=1e-8):
    nu, nv = np.linalg.norm(u), np.linalg.norm(v)
    if nu < eps or nv < eps: return np.nan
    return float(np.degrees(np.arccos(np.clip(np.dot(u, v)/(nu*nv), -1.0, 1.0))))

def pelvis_width_xy(P2):
    d = np.linalg.norm(P2[LM['L_HP']] - P2[LM['R_HP']])
    return float(d) if d > 1e-8 else np.nan

def estimate_floor_y(P2, H=None):
    # use ankles; add heels/toes if available
    ylist = [P2[LM['L_AN'],1], P2[LM['R_AN'],1]]
    if P2.shape[0] >= 33:
        # 29,30 heels; 31,32 big toes (MediaPipe)
        for idx in (29,30,31,32):
            if idx < P2.shape[0]: ylist.append(P2[idx,1])
    y = np.array(ylist, dtype=float)
    y = y[np.isfinite(y)]
    if y.size == 0: return float(H*0.98) if H is not None else np.nan
    return float(np.percentile(y, 95))

def rolling_median(x, k=5):
    s = pd.Series(x, dtype=float)
    return s.rolling(k, center=True, min_periods=1).median().to_numpy()

def central_mask(n_frames, fps, trim_sec=2.0):
    if not fps or fps <= 0: fps = 30.0
    s = int(round(trim_sec*fps))
    lo, hi = s, max(s, n_frames - s)
    m = np.zeros(n_frames, dtype=bool)
    m[lo:hi] = True
    return m

def _baseline(x, n=12):
    x = pd.Series(x, dtype=float)
    return float(x.iloc[:max(3, n)].median(skipna=True))

def _held_at_start(x, thr, n=12):
    s = pd.Series(x, dtype=float).iloc[:max(3, n)]
    return bool((s >= thr).sum() >= max(3, n)//2)

def onset_time_seconds(series_inc_up, fps, amp_thr, z_thresh=0.6, min_frames=3, max_frac=0.3, smooth_k=5):
    s = pd.Series(series_inc_up, dtype=float).rolling(smooth_k, center=True, min_periods=1).median()
    base = _baseline(s, n=12)
    amp  = s - base
    amp_gate = (amp >= amp_thr)
    vel = s.diff()
    vel_std = vel.rolling(7, center=True, min_periods=1).std()
    z = vel / vel_std.replace(0, np.nan)
    vel_gate = (z >= z_thresh)
    gate = (amp_gate & vel_gate)
    n = len(gate); cutoff = int(max_frac*n) if n else 0
    run = 0
    for i, ok in enumerate(gate.fillna(False).to_numpy()):
        if ok:
            run += 1
            if run >= min_frames:
                return (i / float(fps)) if (i <= cutoff) else np.nan
        else:
            run = 0
    return np.nan

def ue_le_delta_t_supine(df, fps,
                         sh_hold_norm=0.02, trunk_hold_deg=10.0, neck_hold_deg=10.0,
                         le_hip_hold_deg=15.0, le_knee_hold_deg=15.0,
                         ue_amp_thr=0.01, le_amp_thr_deg=5.0, zero_tol_s=1/12):
    # UE proxy: pick most dynamic among shoulder height / neck flex / trunk flex
    candidates, names = [], []
    if "shoulder_h" in df: candidates.append(df["shoulder_h"]); names.append("shoulder_h")
    if "neck_flex"  in df: candidates.append(df["neck_flex"]);  names.append("neck_flex")
    if "trunk_flex" in df: candidates.append(df["trunk_flex"]); names.append("trunk_flex")
    if not candidates: return np.nan
    var = [np.nanvar(pd.Series(c, dtype=float)) for c in candidates]
    ue_series = pd.Series(candidates[int(np.nanargmax(var))], dtype=float)

    # LE proxy: prefer hip flexion dynamics; fallback to knee if more dynamic
    hip_mean = np.nanmean(df[["hip_R","hip_L"]].to_numpy(), axis=1)
    knee_mean = np.nanmean(df[["knee_R","knee_L"]].to_numpy(), axis=1)
    le_series = pd.Series(hip_mean if np.nanvar(hip_mean) >= np.nanvar(knee_mean) else knee_mean, dtype=float)

    # held-at-start rules
    ue_held = _held_at_start(df.get("shoulder_h", ue_series), sh_hold_norm) or \
              _held_at_start(df.get("trunk_flex", ue_series), trunk_hold_deg) or \
              _held_at_start(df.get("neck_flex", ue_series), neck_hold_deg)
    le_held = _held_at_start(hip_mean, le_hip_hold_deg) or _held_at_start(knee_mean, le_knee_hold_deg)

    if ue_held and le_held: return 0.0
    if ue_held and not le_held:
        t_le = onset_time_seconds(le_series, fps=fps, amp_thr=le_amp_thr_deg)
        return float(t_le) if pd.notna(t_le) else 0.0
    if (not ue_held) and le_held:
        t_ue = onset_time_seconds(ue_series, fps=fps, amp_thr=ue_amp_thr)
        return -float(t_ue) if pd.notna(t_ue) else 0.0

    t_ue = onset_time_seconds(ue_series, fps=fps, amp_thr=ue_amp_thr)
    t_le = onset_time_seconds(le_series, fps=fps, amp_thr=le_amp_thr_deg)
    if pd.isna(t_ue) or pd.isna(t_le): return np.nan
    dt = float(t_le - t_ue)
    return 0.0 if abs(dt) < zero_tol_s else dt

def chin_tuck_mask(df, fps, neck_thr_deg=12.0, nose_drop_frac=0.08):
    """Chin tuck present when neck_flex >= threshold AND nose->shoulder distance drops >= fraction."""
    base_nose = _baseline(df["nose_sh_dist"], n=12)
    drop_ok = (base_nose - df["nose_sh_dist"]) >= (nose_drop_frac * base_nose)
    return (df["neck_flex"] >= neck_thr_deg) & drop_ok

def measure_supine_flexion_video(video_path, smooth_k=5, model_complexity=1):
    cap = cv2.VideoCapture(video_path)
    fps = cap.get(cv2.CAP_PROP_FPS)
    if not fps or not (10 < fps < 120): fps = 30.0

    rows = []
    with mp.solutions.pose.Pose(model_complexity=model_complexity,
                                min_detection_confidence=0.6,
                                min_tracking_confidence=0.6) as pose:
        while True:
            ok, frame = cap.read()
            if not ok: break
            H, W = frame.shape[:2]
            res = pose.process(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
            if not res.pose_landmarks:
                rows.append([np.nan]*12); continue

            # 2D + world landmarks
            P2 = np.array([[lm.x*W, lm.y*H] for lm in res.pose_landmarks.landmark], dtype=float)
            if res.pose_world_landmarks:
                P3 = np.array([[lm.x, lm.y, lm.z] for lm in res.pose_world_landmarks.landmark], dtype=float)
            else:
                P3 = np.concatenate([P2, np.zeros((P2.shape[0],1))], axis=1)

            # centroids (2D & 3D)
            sh2 = (P2[LM['L_SH']] + P2[LM['R_SH']]) / 2.0
            hp2 = (P2[LM['L_HP']] + P2[LM['R_HP']]) / 2.0
            sh3 = (P3[LM['L_SH']] + P3[LM['R_SH']]) / 2.0
            hp3 = (P3[LM['L_HP']] + P3[LM['R_HP']]) / 2.0

            # choose head landmark (avg ears else nose)
            if np.isfinite(P3[LM['L_EAR']]).all() and np.isfinite(P3[LM['R_EAR']]).all():
                head3 = (P3[LM['L_EAR']] + P3[LM['R_EAR']]) / 2.0
            else:
                head3 = P3[LM['NOSE']]

            head2 = (P2[LM['L_EAR']] + P2[LM['R_EAR']]) / 2.0 if np.isfinite(P2[LM['L_EAR']]).all() and np.isfinite(P2[LM['R_EAR']]).all() \
                    else P2[LM['NOSE']]

            # ---- angles ----
            # Neck flexion: relative (Head–Shoulder vs. Shoulder–MidHip) in 2D (camera-tilt robust)
            neck_flex  = min(angle_between(sh2 - hp2, head2 - sh2), 90.0)

            # NEW trunk flexion (shoulder vertex): 180° - ∠(Head, Shoulder, MidHip) in 3D
            tf_int = angle_3pt(head3, sh3, hp3)   # internal angle at the shoulder
            trunk_flex = max(0.0, 180.0 - tf_int) # grows as the child curls

            # Hip/Knee flexion (3-point, world)
            hip_R  = max(0.0, 180.0 - angle_3pt(P3[LM['R_SH']], P3[LM['R_HP']], P3[LM['R_KN']]))
            hip_L  = max(0.0, 180.0 - angle_3pt(P3[LM['L_SH']], P3[LM['L_HP']], P3[LM['L_KN']]))
            knee_R = max(0.0, 180.0 - angle_3pt(P3[LM['R_HP']], P3[LM['R_KN']], P3[LM['R_AN']]))
            knee_L = max(0.0, 180.0 - angle_3pt(P3[LM['L_HP']], P3[LM['L_KN']], P3[LM['L_AN']]))

            # floor + normalization (2D)
            y_floor = estimate_floor_y(P2, H=H)
            px_scale = pelvis_width_xy(P2) or np.nan
            sh_h = (y_floor - float(sh2[1])) / px_scale if np.isfinite(px_scale) else np.nan
            sh_h = max(sh_h, 0.0) if np.isfinite(sh_h) else np.nan

            # chin-tuck proxy
            ns_dist = np.linalg.norm((P2[LM['NOSE']] if np.isfinite(P2[LM['NOSE']]).all() else head2) - sh2) / px_scale if np.isfinite(px_scale) else np.nan

            # timing proxies (raw)
            sh_y     = float(sh2[1])
            wr_min_y = float(min(P2[LM['L_WR'],1], P2[LM['R_WR'],1]))

            rows.append([neck_flex, trunk_flex, hip_R, hip_L, knee_R, knee_L,
                         sh_h, ns_dist, y_floor, px_scale, sh_y, wr_min_y])

    cap.release()
    cols = ["neck_flex","trunk_flex","hip_R","hip_L","knee_R","knee_L",
            "shoulder_h","nose_sh_dist","y_floor","pelvis_px","sh_y","wr_min_y"]
    df = pd.DataFrame(rows, columns=cols)

    # smooth kinematic series (keep timing proxies raw)
    for k in ["neck_flex","trunk_flex","hip_R","hip_L","knee_R","knee_L","shoulder_h","nose_sh_dist"]:
        df[k] = pd.Series(df[k]).rolling(smooth_k, center=True, min_periods=1).median()

    return df, float(fps)

def summarize_supine_clip(df: pd.DataFrame, fps: float, trim_sec=0.0):
    n = len(df)
    # No trimming now
    m = central_mask(n, fps, trim_sec=trim_sec)  # trim_sec=0 → all frames

    # choose reporting leg by larger median hip flexion
    medR = float(np.nanmedian(pd.Series(df.loc[m, "hip_R"])))
    medL = float(np.nanmedian(pd.Series(df.loc[m, "hip_L"])))
    leg  = "R" if medR >= medL else "L"

    clip = lambda a, lo, hi: np.clip(a.astype(float), lo, hi)

    summary = dict(
        neck_mean_deg   = float(np.nanmean(clip(df.loc[m,"neck_flex"].to_numpy(), 0, 45))),
        trunk_mean_deg  = float(np.nanmean(clip(df.loc[m,"trunk_flex"].to_numpy(), 0, 80))),
        hip_mean_deg    = float(np.nanmean(clip(df.loc[m,f"hip_{leg}"].to_numpy(), 0, 120))),
        knee_mean_deg   = float(np.nanmean(clip(df.loc[m,f"knee_{leg}"].to_numpy(), 0, 135))),
        shoulder_h_mean_norm = float(np.nanmean(df.loc[m,"shoulder_h"])),
        leg_used=leg,
        analysis_frames=int(m.sum()),
        total_frames=n,
        hold_duration_s = float(n/(fps if fps else 30.0))
    )

    # chin-tuck
    ct_mask = chin_tuck_mask(df, fps)
    summary["chin_tuck_present"] = bool(ct_mask[m].any())
    summary["chin_tuck_time_s"]  = float(ct_mask[m].sum() / (fps if fps else 30.0))

    return summary

def export_supine_bestframe_overlay(video_path, df, summ, out_png, model_complexity=2):
    cap = cv2.VideoCapture(video_path)
    fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
    m = central_mask(len(df), fps, trim_sec=2.0)
    idx = int(np.nanargmax(np.where(m, df["trunk_flex"].to_numpy(), -1)))
    cap.set(cv2.CAP_PROP_POS_FRAMES, idx)
    ok, frame = cap.read()
    cap.release()
    if not ok: return

    H, W = frame.shape[:2]
    ov = frame.copy()
    cv2.rectangle(ov, (10,10), (W-10, 130), (0,0,0), -1)
    frame = cv2.addWeighted(ov, 0.35, frame, 0.65, 0)

    def put(y, txt): cv2.putText(frame, txt, (20,y), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255,255,255), 2, cv2.LINE_AA)
    put(40,  f"Neck flex (mean): {summ['neck_mean_deg']:.1f}°")
    put(65,  f"Trunk flex (mean): {summ['trunk_mean_deg']:.1f}°")
    put(90,  f"Hip/Knee flex (mean): {summ['hip_mean_deg']:.1f}° / {summ['knee_mean_deg']:.1f}°")
    put(115, f"Shoulder height: {summ['shoulder_h_mean_norm']:.3f} (norm)")
    cv2.imwrite(out_png, frame)

