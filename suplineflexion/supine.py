def _nearest_frame_with_landmarks(cap, start_idx, max_jump=20, model_complexity=2):
    """Seek around start_idx until a frame returns pose_landmarks."""
    with mp_pose.Pose(static_image_mode=True, model_complexity=model_complexity) as pose:
        for off in range(0, max_jump+1):
            for sgn in (+1, -1) if off>0 else (+1,):
                i = start_idx + sgn*off
                if i < 0: continue
                cap.set(cv2.CAP_PROP_POS_FRAMES, i)
                ok, frame = cap.read()
                if not ok: continue
                res = pose.process(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
                if res.pose_landmarks:
                    return i, frame, res.pose_landmarks
    return None, None, None

