def estimate_floor_y(P2, H=None):
    ylist = [P2[LM['L_AN'],1], P2[LM['R_AN'],1]]
    # add heels and foot indices if available (Pose has 29,30 = heels; 31,32 = big toes)
    if P2.shape[0] >= 33:
        ylist += [P2[29,1], P2[30,1], P2[31,1], P2[32,1]]
    y = np.array(ylist, dtype=float)
    y = y[np.isfinite(y)]
    if y.size == 0:
        return float(H*0.98) if H is not None else np.nan  # bottom-of-frame fallback
    return float(np.percentile(y, 95))


def rolling_median(x, k=5):
    s = pd.Series(x, dtype=float)
    return s.rolling(k, center=True, min_periods=1).median().to_numpy()

def _baseline(x, n=12):
    """Median of the first n frames; robust when clips start near rest/hold."""
    x = pd.Series(x, dtype=float)
    return float(x.iloc[:max(3, n)].median(skipna=True))

def _held_at_start(metric_increasing_when_up, thr, n=12):
    """True if the first n frames are already above the 'hold' threshold."""
    x = pd.Series(metric_increasing_when_up, dtype=float)
    return bool((x.iloc[:max(3, n)] >= thr).sum() >= max(3, n)//2)

def onset_time_seconds(series_inc_up, fps, amp_thr, z_thresh=0.6, min_frames=3, max_frac=0.4, smooth_k=5):
    """
    Detect first sustained upward movement in a metric that INCREASES when the body part moves up.
    Combines amplitude gate (>= amp_thr above baseline) + velocity z-threshold.
    Returns time (s) or np.nan. Ignores onsets detected very late (trimmed clips).
    """
    s = pd.Series(series_inc_up, dtype=float).rolling(smooth_k, center=True, min_periods=1).median()
    base = _baseline(s, n=12)
    # amplitude gate
    amp = s - base
    amp_gate = (amp >= amp_thr)

    # velocity gate
    vel = s.diff()
    vel_std = vel.rolling(7, center=True, min_periods=1).std()
    z = vel / vel_std.replace(0, np.nan)
    vel_gate = (z >= z_thresh)

    gate = (amp_gate & vel_gate)
    n = len(gate)
    cutoff = int(max_frac * n) if n else 0

    run = 0
    for i, ok in enumerate(gate.fillna(False).to_numpy()):
        if ok:
            run += 1
            if run >= min_frames:
                return (i / float(fps)) if (i <= cutoff) else np.nan
        else:
            run = 0
    return np.nan

def ue_le_delta_t_seconds(df, fps,
                          neck_hold_deg=15.0, trunk_hold_deg=5.0, thigh_hold_norm=0.05,
                          ue_amp_thr_deg=3.0,    # neck must rise ≥3° from baseline
                          le_amp_thr_norm=0.02   # thigh height must rise ≥0.02 (pelvis-width-normalized)
                          ):
    """
    UE metric: prefer NECK angle (already increases when head/chest lift); fallback to -wrist_y or -shoulder_y.
    LE metric: max(thigh_R, thigh_L) – increases with thigh lift.
    Rules:
      • If BOTH are already in hold near t=0 → Δt = 0.0
      • If only one is held at t=0 → onset is time for the other
      • Else detect both onsets with amplitude + velocity gates
    """
    # --- UE series (increasing when up) ---
    ue_candidates = []
    if "neck" in df.columns:
        ue_candidates.append(df["neck"])
    if "wr_min_y" in df.columns:
        ue_candidates.append(-df["wr_min_y"])  # y↓ is up → negate so it increases
    if "sh_y" in df.columns:
        ue_candidates.append(-df["sh_y"])

    if not ue_candidates or not {"thigh_R","thigh_L"}.issubset(df.columns):
        return np.nan

    # pick most dynamic UE proxy
    ue_stack = np.vstack([pd.Series(s, dtype=float).to_numpy() for s in ue_candidates])
    ue_series = ue_candidates[int(np.nanargmax(np.nanvar(ue_stack, axis=1)))]

    # LE series: distal 1/3 thigh height (already normalized)
    le_series = df[["thigh_R","thigh_L"]].max(axis=1)

    # --- held-at-start checks (use simple absolute thresholds) ---
    ue_held = _held_at_start(ue_series, thr=neck_hold_deg) or _held_at_start(df.get("trunk", ue_series), thr=trunk_hold_deg)
    le_held = _held_at_start(le_series, thr=thigh_hold_norm)

    if ue_held and le_held:
        return 0.0
    if ue_held and not le_held:
        t_le = onset_time_seconds(le_series, fps=fps, amp_thr=le_amp_thr_norm)
        return float(t_le) if pd.notna(t_le) else 0.0
    if (not ue_held) and le_held:
        t_ue = onset_time_seconds(ue_series, fps=fps, amp_thr=ue_amp_thr_deg)
        return float(t_ue) if pd.notna(t_ue) else 0.0

    # neither held at t=0 → detect both
    t_ue = onset_time_seconds(ue_series, fps=fps, amp_thr=ue_amp_thr_deg)
    t_le = onset_time_seconds(le_series, fps=fps, amp_thr=le_amp_thr_norm)
    if pd.isna(t_ue) or pd.isna(t_le):
        return np.nan
    return float(t_le - t_ue)

def measure_prone_extension_video(video_path, smooth_k=5, model_complexity=1):
    cap = cv2.VideoCapture(video_path)
    fps = cap.get(cv2.CAP_PROP_FPS)
    if not fps or not (10 < fps < 120): fps = 30.0

    rows = []
    with mp_pose.Pose(model_complexity=model_complexity,
                      min_detection_confidence=0.6,
                      min_tracking_confidence=0.6) as pose:
        while True:
            ok, frame = cap.read()
            if not ok: break
            H, W = frame.shape[:2]
            res = pose.process(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
            if not res.pose_landmarks:
                rows.append([np.nan]*13); continue

            P2 = np.array([[lm.x*W, lm.y*H] for lm in res.pose_landmarks.landmark], dtype=float)
            if res.pose_world_landmarks:
                P3 = np.array([[lm.x, lm.y, lm.z] for lm in res.pose_world_landmarks.landmark], dtype=float)
            else:
                P3 = np.concatenate([P2, np.zeros((P2.shape[0],1))], axis=1)

            sh2 = (P2[LM['L_SH']] + P2[LM['R_SH']]) / 2.0
            hp2 = (P2[LM['L_HP']] + P2[LM['R_HP']]) / 2.0
            head2 = (P2[LM['L_EAR']] + P2[LM['R_EAR']]) / 2.0

            neck_rel = angle_between(sh2 - hp2, head2 - sh2)
            neck_deg = min(neck_rel, 90.0)
            trunk_deg = max(0.0, 90.0 - angle_to_vertical(hp2, sh2))

            hip_R  = hip_extension_from_internal(angle_3pt(P3[LM['R_SH']], P3[LM['R_HP']], P3[LM['R_KN']]))
            hip_L  = hip_extension_from_internal(angle_3pt(P3[LM['L_SH']], P3[LM['L_HP']], P3[LM['L_KN']]))
            knee_R = knee_flexion_from_internal(angle_3pt(P3[LM['R_HP']], P3[LM['R_KN']], P3[LM['R_AN']]))
            knee_L = knee_flexion_from_internal(angle_3pt(P3[LM['L_HP']], P3[LM['L_KN']], P3[LM['L_AN']]))

            y_floor = estimate_floor_y(P2)
            px_scale = pelvis_width_xy(P2) or np.nan

            hipR_xy, kneeR_xy = P2[LM['R_HP']], P2[LM['R_KN']]
            hipL_xy, kneeL_xy = P2[LM['L_HP']], P2[LM['L_KN']]
            distalR_xy = hipR_xy + (2.0/3.0)*(kneeR_xy - hipR_xy)
            distalL_xy = hipL_xy + (2.0/3.0)*(kneeL_xy - hipL_xy)

            thigh_R = (y_floor - distalR_xy[1]) / px_scale if np.isfinite(px_scale) else np.nan
            thigh_L = (y_floor - distalL_xy[1]) / px_scale if np.isfinite(px_scale) else np.nan
            thigh_R = max(thigh_R, 0.0) if np.isfinite(thigh_R) else np.nan
            thigh_L = max(thigh_L, 0.0) if np.isfinite(thigh_L) else np.nan

            # NEW: y-series we’ll use for timing (UE/LE onset)
            sh_y     = float(sh2[1])
            wr_min_y = float(min(P2[LM['L_WR'],1], P2[LM['R_WR'],1]))
            an_min_y = float(min(P2[LM['L_AN'],1], P2[LM['R_AN'],1]))

            rows.append([
                neck_deg, trunk_deg, hip_R, hip_L, knee_R, knee_L,
                thigh_R, thigh_L, y_floor, px_scale,
                sh_y, wr_min_y, an_min_y
            ])

    cap.release()
    cols = ["neck","trunk","hip_R","hip_L","knee_R","knee_L",
            "thigh_R","thigh_L","y_floor","pelvis_px",
            "sh_y","wr_min_y","an_min_y"]
    df = pd.DataFrame(rows, columns=cols)

    # jitter smoothing (angles/distances only)
    for k in ["neck","trunk","hip_R","hip_L","knee_R","knee_L","thigh_R","thigh_L"]:
        df[k] = pd.Series(df[k]).rolling(smooth_k, center=True, min_periods=1).median()

    return df, float(fps)

