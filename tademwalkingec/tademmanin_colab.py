    AGE_FILTER = None
    if STUDENT_FILTER is not None:
        manifest = manifest[manifest["student"] == STUDENT_FILTER]
    if AGE_FILTER is not None:
        manifest = manifest[manifest["age"] == AGE_FILTER]
    if len(manifest) == 0:
        raise RuntimeError("No videos to process after filters. Check ROOT / folder naming / manifest.")

    print("Queued:", len(manifest))

    # ---- Pair subjects ----
    paired_rows = []
    for (age, stu), grp in manifest.groupby(["age", "student"]):
        recs = grp.to_dict("records")
        front_path = next((r["video"] for r in recs if r["view"] == "front"), None)  # actually PROFILE in your dataset
        side_path  = next((r["video"] for r in recs if r["view"] == "side"),  None)  # actually FRONT view in your dataset

        # We MUST have a profile video to compute steps/angles/AP sway
        if front_path is None:
            continue

        # swap as per your dataset:
        profile_video = front_path   # Front folder = profile(side view)
        front_video   = side_path    # Side folder = front view (may be None)

        paired_rows.append(dict(
            age=age,
            student=stu,
            side_video=profile_video,   # keep this column name: pipeline compatibility
            front_video=front_video
        ))

    paired = pd.DataFrame(paired_rows)
    print("Paired subjects:", len(paired))
    if len(paired) == 0:
        raise RuntimeError("No paired subjects found. Verify dataset has Front/Side videos per student.")

    # ---- Output buffers ----
    rowsProfile6, rowsProfile7 = [], []
    rowsFront6, rowsFront7 = [], []
    errs = []
    calib_cache = {}

    PERSTEP_DIR = os.path.join(OUTDIR, "PerStep")
    os.makedirs(PERSTEP_DIR, exist_ok=True)

    def flush_excels():
        dfP6 = pd.DataFrame(rowsProfile6)
        dfP7 = pd.DataFrame(rowsProfile7)
        dfF6 = pd.DataFrame(rowsFront6)
        dfF7 = pd.DataFrame(rowsFront7)
        dfe  = pd.DataFrame(errs)

        XLS_P6   = os.path.join(OUTDIR, "TW_profile_6yrs_ec.xlsx")
        XLS_P7   = os.path.join(OUTDIR, "TW_profile_7yrs_ec.xlsx")
        XLS_F6   = os.path.join(OUTDIR, "TW_front_6yrs_ec.xlsx")
        XLS_F7   = os.path.join(OUTDIR, "TW_front_7yrs_ec.xlsx")
        XLS_PALL = os.path.join(OUTDIR, "TW_profile_AllAges_ec.xlsx")
        XLS_FALL = os.path.join(OUTDIR, "TW_front_AllAges_ec.xlsx")

        if len(dfP6): dfP6.to_excel(XLS_P6, index=False)
        if len(dfP7): dfP7.to_excel(XLS_P7, index=False)
        if len(dfF6): dfF6.to_excel(XLS_F6, index=False)
        if len(dfF7): dfF7.to_excel(XLS_F7, index=False)

        if len(dfP6) or len(dfP7):
            pd.concat([dfP6, dfP7], ignore_index=True).to_excel(XLS_PALL, index=False)
        if len(dfF6) or len(dfF7):
            pd.concat([dfF6, dfF7], ignore_index=True).to_excel(XLS_FALL, index=False)

        if len(dfe):
            dfe.to_csv(os.path.join(OUTDIR, "TW_Errors.csv"), index=False)

        print(f"\n💾 Saved batch → Profile6={len(rowsProfile6)} Profile7={len(rowsProfile7)} Front6={len(rowsFront6)} Front7={len(rowsFront7)} Errors={len(errs)}")

    # ---- Process ----
    batch_size = int(CONFIG.get("BATCH_SIZE", 10))
    pbar = tqdm(paired.iterrows(), total=len(paired), desc="TW", unit="student")

    for idx, (_, row) in enumerate(pbar, start=1):
        pbar.set_description(f"TW {idx}/{len(paired)} | {row['age']} | {str(row['student'])[:18]}")

        res = process_one_tw(row, calib_cache)

        if res[0] == "ok_tw":
            clip_row, df_steps, dfA = res[1], res[2], res[3]
            used_profile = clip_row.get("used_profile_video")
            used_front   = clip_row.get("used_front_video")

            profile_out = dict(
                age=clip_row["age"],
                student=clip_row["student"],
                used_profile_video=os.path.basename(used_profile) if used_profile else None,

                ap_sway_mean_deg=clip_row.get("ap_sway_mean_deg"),
                ap_sway_sd_deg=clip_row.get("ap_sway_sd_deg"),
                ap_sway_peak_deg=clip_row.get("ap_sway_peak_deg"),

                median_gap_cm=clip_row.get("median_gap_cm"),
                mean_step_gap_cm=clip_row.get("mean_gap_detected_cm"),
                n_L_contacts=clip_row.get("n_L_contacts"),
                n_R_contacts=clip_row.get("n_R_contacts"),
                n_steps_used=clip_row.get("n_steps_used"),
                n_understeps=clip_row.get("n_understeps"),

                neck_mean_deg=clip_row.get("neck_mean_detected_deg"),
                trunk_mean_deg=clip_row.get("trunk_mean_detected_deg"),
                hip_mean_deg=clip_row.get("hip_mean_detected_deg"),
                knee_mean_deg=clip_row.get("knee_mean_detected_deg"),
            )

            front_out = dict(
                age=clip_row["age"],
                student=clip_row["student"],
                used_front_video=os.path.basename(used_front) if used_front else None,

                ml_sway_mean_deg=clip_row.get("ml_sway_mean_deg"),
                ml_sway_sd_deg=clip_row.get("ml_sway_sd_deg"),
                ml_sway_peak_deg=clip_row.get("ml_sway_peak_deg"),
            )

            if CONFIG.get("VERBOSE", False):
                tqdm.write(f"\n✓ TW OK | {clip_row['age']} | {clip_row['student']}")
                tqdm.write(f"  used profile: {os.path.basename(used_profile) if used_profile else 'NA'}")
                tqdm.write(f"  used front:   {os.path.basename(used_front) if used_front else 'NA'}")
                tqdm.write(
                    f"  PROFILE AP sway mean={clip_row.get('ap_sway_mean_deg', float('nan')):.2f} "
                    f"sd={clip_row.get('ap_sway_sd_deg', float('nan')):.2f} "
                    f"peak={clip_row.get('ap_sway_peak_deg', float('nan')):.2f}"
                )
                tqdm.write(
                    f"  STEPS nL={clip_row.get('n_L_contacts')} nR={clip_row.get('n_R_contacts')} "
                    f"used={clip_row.get('n_steps_used')} under={clip_row.get('n_understeps')} "
                    f"median_gap_cm={clip_row.get('median_gap_cm')}"
                )
                tqdm.write(
                    f"  ANG   neck={profile_out['neck_mean_deg']} trunk={profile_out['trunk_mean_deg']} "
                    f"hip={profile_out['hip_mean_deg']} knee={profile_out['knee_mean_deg']}"
                )

                if CONFIG.get("PRINT_STEPS_PREVIEW", 0) and len(df_steps):
                    nprev = int(CONFIG.get("PRINT_STEPS_PREVIEW", 5))
                    prev = df_steps.head(nprev)[["i","foot","step_gap_cm","nsd","understep","hgtd_cm"]]
                    tqdm.write("  steps preview:\n" + prev.to_string(index=False))

            if CONFIG.get("SAVE_PER_STEP_FILES", False):
                tag = f"{clip_row['age']}_{clip_row['student']}".replace("/", "_")
                df_steps.to_excel(os.path.join(PERSTEP_DIR, f"{tag}_StepGaps.xlsx"), index=False)
                dfA.to_excel(os.path.join(PERSTEP_DIR, f"{tag}_Angles.xlsx"), index=False)

            if clip_row["age"] == "6yrs":
                rowsProfile6.append(profile_out)
                rowsFront6.append(front_out)
            else:
                rowsProfile7.append(profile_out)
                rowsFront7.append(front_out)

        else:
            errs.append(res[1])
            tqdm.write(f"\n✘ TW ERR | {row['age']} | {row['student']} | {res[1].get('error')}")

        if (idx % batch_size == 0) or (idx == len(paired)):
            flush_excels()

