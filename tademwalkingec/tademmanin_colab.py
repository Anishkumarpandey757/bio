# -------------------- small helpers --------------------
def _finite(a):
    a = np.asarray(a, dtype=float)
    return a[np.isfinite(a)]

def _nanmedian_safe(x):
    x = _finite(x)
    return float(np.nanmedian(x)) if x.size else None

def _mean_safe(x):
    x = _finite(x)
    return float(np.nanmean(x)) if x.size else None

def _wrap_deg(a):
    a = (a + 180.0) % 360.0 - 180.0
    return a

def _P2(df: pd.DataFrame, idx: int) -> np.ndarray:
    """Nx2 pixel coords for landmark idx."""
    cx, cy = f"x{idx}", f"y{idx}"
    if cx not in df.columns or cy not in df.columns:
        return np.full((len(df), 2), np.nan, dtype=float)
    return np.column_stack([df[cx].to_numpy(float), df[cy].to_numpy(float)])

def _P2N(df: pd.DataFrame, idx: int) -> np.ndarray:
    """Nx2 normalized coords for landmark idx."""
    cx, cy = f"xn{idx}", f"yn{idx}"
    if cx not in df.columns or cy not in df.columns:
        return np.full((len(df), 2), np.nan, dtype=float)
    return np.column_stack([df[cx].to_numpy(float), df[cy].to_numpy(float)])

def _mid(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    return (np.asarray(a, float) + np.asarray(b, float)) / 2.0

def angle_3pt(a, b, c, eps=1e-8) -> float:
    """Angle ABC (in degrees). Works for 2D or 3D."""
    a = np.asarray(a, float); b = np.asarray(b, float); c = np.asarray(c, float)
    if not (np.isfinite(a).all() and np.isfinite(b).all() and np.isfinite(c).all()):
        return float("nan")
    ba = a - b
    bc = c - b
    nba = np.linalg.norm(ba)
    nbc = np.linalg.norm(bc)
    if nba < eps or nbc < eps:
        return float("nan")
    cosang = float(np.dot(ba, bc) / (nba * nbc))
    cosang = np.clip(cosang, -1.0, 1.0)
    return float(np.degrees(np.arccos(cosang)))

def angle_to_vertical(p0, p1) -> float:
    """Angle of vector (p0 -> p1) relative to vertical axis (degrees)."""
    p0 = np.asarray(p0, float); p1 = np.asarray(p1, float)
    if not (np.isfinite(p0).all() and np.isfinite(p1).all()):
        return float("nan")
    v = p1 - p0
    # vertical reference is (0, -1) in image coords (y down)
    vert = np.array([0.0, -1.0], float)
    ang = angle_3pt(p0 + vert, p0, p1)  # angle between vert and v
    return float(ang)

def _head_point_2d(df: pd.DataFrame, k: int) -> Optional[np.ndarray]:
    """Best available head point at frame k."""
    def get(idx):
        cx, cy = f"x{idx}", f"y{idx}"
        if cx in df.columns and cy in df.columns:
            p = np.array([df.at[k, cx], df.at[k, cy]], dtype=float)
            return p if np.isfinite(p).all() else None
        return None
    for key in ["NOSE", "L_EYE", "R_EYE", "L_EAR", "R_EAR"]:
        if key in LM:
            p = get(LM[key])
            if p is not None:
                return p
    return None

# -------------------- Pose extraction --------------------
def run_pose_fast(
    video_path: str,
    frame_stride: int = 2,
    downscale: float = 1.0,
    model_complexity: int = 1,
    max_frames: Optional[int] = None,
    include_world: bool = True,
) -> Tuple[pd.DataFrame, float]:
    """
    Returns (df, fps). df has columns:
      i, t, w, h,
      x{idx}, y{idx}, xn{idx}, yn{idx}, vis{idx},
      and optionally xw{idx}, yw{idx}, zw{idx} for world coords.
    Never returns None. On failure, returns empty df and fps=30.
    """
    if not isinstance(video_path, str) or not os.path.exists(video_path):
        return pd.DataFrame(), 30.0

    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        return pd.DataFrame(), 30.0

    fps = cap.get(cv2.CAP_PROP_FPS)
    fps = float(fps) if fps and fps > 1e-3 else 30.0

    pose = mp_pose.Pose(
        static_image_mode=False,
        model_complexity=int(model_complexity),
        enable_segmentation=False,
        smooth_landmarks=True,
        min_detection_confidence=0.5,
        min_tracking_confidence=0.5,
    )

    rows = []
    frame_idx = 0
    kept = 0

    try:
        while True:
            ok, frame = cap.read()
            if not ok:
                break
            if frame_idx % int(max(1, frame_stride)) != 0:
                frame_idx += 1
                continue

            h0, w0 = frame.shape[:2]
            if downscale and float(downscale) != 1.0:
                frame = cv2.resize(frame, (int(w0 * downscale), int(h0 * downscale)), interpolation=cv2.INTER_AREA)
            h, w = frame.shape[:2]

            rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            res = pose.process(rgb)

            row = {"i": int(frame_idx), "t": float(frame_idx) / fps, "w": int(w), "h": int(h)}

            if res.pose_landmarks:
                lms = res.pose_landmarks.landmark
                for name, idx in LM.items():
                    lm = lms[idx]
                    xn, yn = float(lm.x), float(lm.y)
                    row[f"xn{idx}"] = xn
                    row[f"yn{idx}"] = yn
                    row[f"x{idx}"] = xn * w
                    row[f"y{idx}"] = yn * h
                    row[f"vis{idx}"] = float(lm.visibility)
            else:
                # fill NaNs
                for name, idx in LM.items():
                    row[f"xn{idx}"] = np.nan
                    row[f"yn{idx}"] = np.nan
                    row[f"x{idx}"] = np.nan
                    row[f"y{idx}"] = np.nan
                    row[f"vis{idx}"] = np.nan

            if include_world and res.pose_world_landmarks:
                wlms = res.pose_world_landmarks.landmark
                for name, idx in LM.items():
                    wlm = wlms[idx]
                    row[f"xw{idx}"] = float(wlm.x)
                    row[f"yw{idx}"] = float(wlm.y)
                    row[f"zw{idx}"] = float(wlm.z)

            rows.append(row)
            kept += 1
            frame_idx += 1
            if max_frames is not None and kept >= int(max_frames):
                break
    except Exception:
        # return what we have
        pass
    finally:
        cap.release()
        pose.close()

    df = pd.DataFrame(rows)
    return df, fps

# -------------------- Axis + calibration --------------------
def infer_walk_axis_from_midhip(df: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray]:
    """PCA on mid-hip pixel trajectory -> (origin, unit axis)."""
    hip = _mid(_P2(df, LM["L_HP"]), _P2(df, LM["R_HP"]))
    ok = np.isfinite(hip).all(axis=1)
    H = hip[ok]
    if H.shape[0] < 5:
        # fallback: vertical axis
        origin = np.nanmedian(hip, axis=0)
        axis = np.array([0.0, 1.0], float)
        return origin, axis

    Hc = H - np.mean(H, axis=0, keepdims=True)
    cov = np.cov(Hc.T)
    w, V = np.linalg.eig(cov)
    axis = V[:, int(np.argmax(w))].astype(float)
    axis = axis / (np.linalg.norm(axis) + 1e-9)

    origin = np.nanmedian(H, axis=0).astype(float)

    # choose sign: projection should increase over time
    proj = (hip - origin) @ axis
    proj_ok = proj[np.isfinite(proj)]
    if proj_ok.size >= 2 and proj_ok[-1] < proj_ok[0]:
        axis = -axis

    return origin, axis

def calibrate_side(video_path: str):
    """Calibrate walking axis/origin for the PROFILE (side) view.

    We keep axis/origin inference (needed for stable axis-projected distances),
    but we intentionally DO NOT set pixels-per-cm (ppc) here.

    Why ppc is not calibrated here:
    - Estimating ppc from how far the CHILD moves in the frame is not a fixed physical reference.
      If the child doesn't span the full 250 cm mat in the visible frames (or frames are missed),
      ppc becomes too small and step gaps explode (150–190 cm artifacts).
    - We estimate ppc later inside compute_step_metrics() using robust CONTACT-range/ HIP-range percentiles.

    Returns dict:
      origin: 2D pixels (reference point)
      axis:   2D unit vector (walking direction in image)
      ppc:    NaN (computed later)
    """
    import numpy as np
    import cv2

    # Light pose pass to infer axis/origin
    try:
        df, fps = run_pose_fast(
            video_path,
            frame_stride=int(CONFIG.get("CALIB_FRAME_STRIDE", max(1, CONFIG.get("FRAME_STRIDE", 1)))),
            downscale=float(CONFIG.get("DOWNSCALE", 1.0)),
            model_complexity=int(CONFIG.get("MODEL_COMPLEXITY", 1)),
            max_frames=int(CONFIG.get("CALIB_MAX_FRAMES", 250)),
            include_world=False
        )
    except Exception:
        df, fps = None, None

    # Default origin/axis from first frame if pose fails
    cap = cv2.VideoCapture(video_path)
    ok, frame = cap.read()
    cap.release()
    if ok and frame is not None:
        h, w = frame.shape[:2]
        origin0 = np.array([w / 2.0, h / 2.0], dtype=float)
    else:
        origin0 = np.array([0.0, 0.0], dtype=float)

    axis0 = np.array([0.0, 1.0], dtype=float)

    if df is None or len(df) < 10:
        return dict(origin=origin0, axis=axis0, ppc=float('nan'))

    # Mid-hip points over time
    LHP = _P2(df, LM["L_HP"])
    RHP = _P2(df, LM["R_HP"])
    hip_mid = (LHP + RHP) / 2.0
    good = np.isfinite(hip_mid).all(axis=1)

    if good.sum() < 10:
        return dict(origin=origin0, axis=axis0, ppc=float('nan'))

    pts = hip_mid[good]

    # Origin = robust center of motion (median)
    origin = np.nanmedian(pts, axis=0)

    # Axis = first principal component of motion (PCA on centered points)
    X = pts - origin
    # If motion is tiny, keep default axis
    if np.nanstd(X[:, 0]) < 1e-3 and np.nanstd(X[:, 1]) < 1e-3:
        axis = axis0
    else:
        C = np.cov(X.T)
        vals, vecs = np.linalg.eigh(C)
        axis = vecs[:, int(np.nanargmax(vals))]
        axis = axis / (np.linalg.norm(axis) + 1e-9)

    return dict(origin=origin, axis=axis, ppc=float('nan'))

def calibrate_front(front_video: Optional[str]) -> Optional[Dict[str, object]]:
    if not front_video or not os.path.exists(front_video):
        return None
    df, fps = run_pose_fast(
        front_video,
        frame_stride=int(CONFIG["FRAME_STRIDE"]),
        downscale=float(CONFIG["DOWNSCALE"]),
        model_complexity=int(CONFIG["MODEL_COMPLEXITY"]),
        max_frames=CONFIG.get("MAX_FRAMES", None),
        include_world=False,
    )
    if df is None or len(df) < 10:
        return None
    origin, axis = infer_walk_axis_from_midhip(df)
    return {"origin": origin, "axis": axis, "fps": fps}

# -------------------- Sway metrics --------------------
def trunk_sway_from_baseline(df: pd.DataFrame) -> np.ndarray:
    """Angle of trunk vector (mid-hip->mid-shoulder) across frames, baseline-subtracted (degrees)."""
    SHO = _mid(_P2(df, LM["L_SH"]), _P2(df, LM["R_SH"]))
    HIP = _mid(_P2(df, LM["L_HP"]), _P2(df, LM["R_HP"]))
    v = SHO - HIP
    theta = np.degrees(np.arctan2(v[:, 1], v[:, 0]))
    if not np.any(np.isfinite(theta)):
        return np.full_like(theta, np.nan, dtype=float)
    base = float(np.nanmedian(theta))
    dev = _wrap_deg(theta - base)
    return dev

# -------------------- Step detection (velocity stability) --------------------
@dataclass
class ContactEvent:
    frame_idx: int   # row index in df
    foot: str        # "L" or "R"

def detect_contacts_velocity_stability(
    df: pd.DataFrame,
    fps: float,
    window: int = 5,
    vel_thresh_norm: float = 0.002,
    min_gap_frames: int = 5,
    vis_thresh: float = 0.3
) -> Tuple[List[ContactEvent], int, int]:
    """
    Detect contact instants using toe (FOOT_INDEX) stability in normalized coords.
    - stability: velocity < threshold for 'window' consecutive frames
    - emits an event only on rising edge of stability
    - enforces alternating contacts and a minimum frame gap between events
    """
    L_toe = _P2N(df, LM["L_TOE"])
    R_toe = _P2N(df, LM["R_TOE"])
    L_vis = df.get(f"vis{LM['L_TOE']}", pd.Series([np.nan]*len(df))).to_numpy(float)
    R_vis = df.get(f"vis{LM['R_TOE']}", pd.Series([np.nan]*len(df))).to_numpy(float)

    def vel(p, pprev):
        if not (np.isfinite(p).all() and np.isfinite(pprev).all()):
            return np.nan
        return float(np.hypot(p[0] - pprev[0], p[1] - pprev[1]))

    Lbuf, Rbuf = deque(maxlen=window), deque(maxlen=window)
    prev_L_stable = False
    prev_R_stable = False
    last_contact: Optional[str] = None
    last_event_frame = -10**9

    events: List[ContactEvent] = []
    nL = nR = 0

    for k in range(1, len(df)):
        lv = vel(L_toe[k], L_toe[k-1])
        rv = vel(R_toe[k], R_toe[k-1])

        # if visibility low or invalid -> reset buffers
        if not np.isfinite(lv) or not (np.isfinite(L_toe[k]).all()) or L_vis[k] < vis_thresh:
            Lbuf.clear()
            L_stable = False
        else:
            Lbuf.append(lv)
            L_stable = (len(Lbuf) == window and all((x < vel_thresh_norm) for x in Lbuf))

        if not np.isfinite(rv) or not (np.isfinite(R_toe[k]).all()) or R_vis[k] < vis_thresh:
            Rbuf.clear()
            R_stable = False
        else:
            Rbuf.append(rv)
            R_stable = (len(Rbuf) == window and all((x < vel_thresh_norm) for x in Rbuf))

        # rising edges only
        L_edge = (L_stable and not prev_L_stable)
        R_edge = (R_stable and not prev_R_stable)

        if (k - last_event_frame) < int(min_gap_frames):
            L_edge = False
            R_edge = False

        # First contact: choose whichever stabilizes first
        if last_contact is None:
            if L_edge and not R_edge:
                events.append(ContactEvent(k, "L"))
                last_contact = "L"
                last_event_frame = k
                nL += 1
            elif R_edge and not L_edge:
                events.append(ContactEvent(k, "R"))
                last_contact = "R"
                last_event_frame = k
                nR += 1
            elif L_edge and R_edge:
                # both: pick lower instantaneous velocity (more stable)
                if lv <= rv:
                    events.append(ContactEvent(k, "L")); last_contact="L"; nL += 1
                else:
                    events.append(ContactEvent(k, "R")); last_contact="R"; nR += 1
                last_event_frame = k
        else:
            # Alternating contacts
            if L_edge and last_contact == "R":
                events.append(ContactEvent(k, "L"))
                last_contact = "L"
                last_event_frame = k
                nL += 1
            elif R_edge and last_contact == "L":
                events.append(ContactEvent(k, "R"))
                last_contact = "R"
                last_event_frame = k
                nR += 1

        prev_L_stable = L_stable
        prev_R_stable = R_stable

    return events, nL, nR
CONFIG["EXPECTED_FOOT_LEN_CM"] = 18.0    # child (6–7 yrs)
CONFIG["EXPECTED_HIP_WIDTH_CM"] = 18.0   # fallback
CONFIG["MAX_TANDEM_GAP_CM"] = 5.0


def compute_step_metrics(df, placements, origin, axis, ppc_unused):
    """
    Tandem Walking step metrics (patched to produce 0–5 cm gaps).

    Key fix:
      step_gap_cm is NOT heel-to-heel stride.
      step_gap_cm = max(0, projection(lead_heel(f1) - prev_toe(f0), axis)) in cm

    Outputs:
      - i, frame_idx, foot
      - step_gap_cm : tandem heel-to-toe spacing (0–MAX_TANDEM_GAP_CM else None)
      - nsd         : stride_px / leading_foot_len_px
      - understep
      - hgtd_cm     : signed heel-to-prev-toe (negative overlap, positive gap)
      - raw_step_px : stride px (heel-to-heel along axis)  [debug]
      - foot_len_px
      - ppc_used
      - outlier
    """
    import numpy as np

    # -------------------------------
    # Helpers
    # -------------------------------
    def _get_frame_foot(ev):
        if isinstance(ev, dict):
            return int(ev["i"]), ev["foot"]
        if isinstance(ev, (list, tuple)) and len(ev) >= 2:
            return int(ev[0]), ev[1]
        if hasattr(ev, "frame_idx") and hasattr(ev, "foot"):
            return int(ev.frame_idx), ev.foot
        raise TypeError(f"Unknown placement type: {type(ev)}")

    def _isfinite2(p):
        return p is not None and np.isfinite(p).all()

    # -------------------------------
    steps = []
    if placements is None or len(placements) < 2:
        return steps

    # Normalize walking axis
    axis = np.asarray(axis, dtype=float)
    n = np.linalg.norm(axis)
    axis = axis / n if np.isfinite(n) and n > 1e-8 else np.array([0.0, 1.0], dtype=float)

    # -------------------------------
    # PPC (px/cm): use override if available, else foot-length, else hip-width fallback
    # -------------------------------
    ppc_used = float("nan")
    if ppc_unused is not None:
        try:
            ppc_tmp = float(ppc_unused)
            if np.isfinite(ppc_tmp) and ppc_tmp > 1e-6:
                ppc_used = ppc_tmp
        except Exception:
            pass

    if not (np.isfinite(ppc_used) and ppc_used > 1e-6):
        EXPECTED_FOOT_CM = float(CONFIG.get("EXPECTED_FOOT_LEN_CM", 18.0))
        EXPECTED_HIP_CM  = float(CONFIG.get("EXPECTED_HIP_WIDTH_CM", 18.0))

        foot_px = []
        hip_px  = []

        for ev in placements:
            f, foot = _get_frame_foot(ev)

            # Foot length at contact (heel->toe) for that same foot
            heel = _P2(df, LM["L_HEEL"] if foot == "L" else LM["R_HEEL"])[f]
            toe  = _P2(df, LM["L_TOE"]  if foot == "L" else LM["R_TOE"])[f]
            if _isfinite2(heel) and _isfinite2(toe):
                d = float(np.linalg.norm(heel - toe))
                if 10.0 < d < 250.0:  # sanity bounds in px
                    foot_px.append(d)

            # Hip width (L_HIP <-> R_HIP) at contact
            LHP = _P2(df, LM["L_HP"])[f]
            RHP = _P2(df, LM["R_HP"])[f]
            if _isfinite2(LHP) and _isfinite2(RHP):
                d = float(np.linalg.norm(LHP - RHP))
                if 10.0 < d < 400.0:
                    hip_px.append(d)

        foot_px = np.asarray(foot_px, float)
        hip_px  = np.asarray(hip_px,  float)

        if foot_px.size >= 3 and EXPECTED_FOOT_CM > 0:
            ppc_used = float(np.nanmedian(foot_px) / EXPECTED_FOOT_CM)
        elif hip_px.size >= 3 and EXPECTED_HIP_CM > 0:
            ppc_used = float(np.nanmedian(hip_px) / EXPECTED_HIP_CM)
        else:
            ppc_used = float("nan")

    MAX_TANDEM_GAP_CM = float(CONFIG.get("MAX_TANDEM_GAP_CM", 5.0))

    # -------------------------------
    # Iterate consecutive placements
    # -------------------------------
    for k in range(1, len(placements)):
        f0, foot0 = _get_frame_foot(placements[k - 1])  # previous contact (trailing)
        f1, foot1 = _get_frame_foot(placements[k])      # current contact (leading)

        # enforce alternation
        if foot0 == foot1:
            continue

        # points we need
        prev_heel = _P2(df, LM["L_HEEL"] if foot0 == "L" else LM["R_HEEL"])[f0]
        prev_toe  = _P2(df, LM["L_TOE"]  if foot0 == "L" else LM["R_TOE"])[f0]

        lead_heel = _P2(df, LM["L_HEEL"] if foot1 == "L" else LM["R_HEEL"])[f1]
        lead_toe  = _P2(df, LM["L_TOE"]  if foot1 == "L" else LM["R_TOE"])[f1]

        if not (_isfinite2(prev_heel) and _isfinite2(prev_toe) and _isfinite2(lead_heel) and _isfinite2(lead_toe)):
            continue

        # stride (heel->heel) along axis (debug + NSD reference)
        stride_px = abs(float(np.dot((lead_heel - prev_heel), axis)))

        # tandem signed gap (lead heel vs prev toe) along axis
        signed_gap_px = float(np.dot((lead_heel - prev_toe), axis))  # negative = overlap, positive = separation
        gap_px = max(0.0, signed_gap_px)  # physiological spacing cannot be negative

        # leading foot length (px)
        foot_len_px = float(np.linalg.norm(lead_heel - lead_toe))
        nsd = (stride_px / foot_len_px) if (np.isfinite(foot_len_px) and foot_len_px > 1e-6) else float("nan")
        understep = bool(np.isfinite(nsd) and nsd < 1.0)

        # convert to cm if we have scale
        if np.isfinite(ppc_used) and ppc_used > 1e-6:
            step_gap_cm = gap_px / ppc_used
            hgtd_cm = signed_gap_px / ppc_used  # signed
        else:
            step_gap_cm = None
            hgtd_cm = None

        # clamp outliers
        outlier = False
        if step_gap_cm is not None and (not np.isfinite(step_gap_cm) or step_gap_cm > MAX_TANDEM_GAP_CM):
            outlier = True
            step_gap_cm = None

        steps.append(dict(
            i=int(df["i"].iloc[f1]) if "i" in df.columns else int(f1),
            frame_idx=int(f1),
            foot=str(foot1),

            step_gap_cm=float(step_gap_cm) if (step_gap_cm is not None and np.isfinite(step_gap_cm)) else None,
            nsd=float(nsd) if np.isfinite(nsd) else None,
            understep=bool(understep),
            hgtd_cm=float(hgtd_cm) if (hgtd_cm is not None and np.isfinite(hgtd_cm)) else None,

            raw_step_px=float(stride_px) if np.isfinite(stride_px) else None,
            foot_len_px=float(foot_len_px) if np.isfinite(foot_len_px) else None,
            ppc_used=float(ppc_used) if (np.isfinite(ppc_used) and ppc_used > 1e-6) else None,
            outlier=bool(outlier),
        ))

    return steps

def process_one_tw(row: pd.Series, calib_cache: dict):
    """
    row must have: age, student, side_video (profile), front_video (front view or None)
    Returns: ("ok_tw", clip_row, df_steps, dfA) OR ("err", err_row)
    """
    import os
    import numpy as np
    import pandas as pd

    age = row.get("age")
    stu = row.get("student")

    profile_video = row.get("side_video")   # profile view (your swapped folder)
    front_video   = row.get("front_video")  # front view (may be None)

    if not isinstance(profile_video, str) or not os.path.exists(profile_video):
        return ("err", dict(age=age, student=stu, error="profile_video_missing"))

    # -------------------- Calibration (cached) --------------------
    key = (age, stu, profile_video, front_video)
    if key not in calib_cache:
        try:
            cS = calibrate_side(profile_video)
        except Exception as e:
            return ("err", dict(age=age, student=stu, error=f"calibrate_side_failed: {e}"))
        try:
            cF = calibrate_front(front_video) if (front_video and os.path.exists(front_video)) else None
        except Exception:
            cF = None
        calib_cache[key] = dict(side=cS, front=cF)

    cS = calib_cache[key]["side"]
    cF = calib_cache[key]["front"]

    # -------------------- Run pose on profile video --------------------
    try:
        df_side, fps = run_pose_fast(
            profile_video,
            frame_stride=int(CONFIG["FRAME_STRIDE"]),
            downscale=float(CONFIG["DOWNSCALE"]),
            model_complexity=int(CONFIG["MODEL_COMPLEXITY"]),
            max_frames=CONFIG.get("MAX_FRAMES", None),
            include_world=True,
        )
    except Exception as e:
        return ("err", dict(age=age, student=stu, error=f"run_pose_fast_profile_failed: {e}"))

    if df_side is None or len(df_side) < 10:
        return ("err", dict(age=age, student=stu, error="too_few_frames_profile"))

    # Ensure df has "i" for frame index
    if "i" not in df_side.columns:
        df_side = df_side.reset_index(drop=True)
        df_side["i"] = np.arange(len(df_side), dtype=int)

    # Robust fps fallback
    if not fps or not np.isfinite(fps) or fps <= 1e-6:
        fps = float(CONFIG.get("FPS_FALLBACK", 30.0))

    # -------------------- AP sway from profile --------------------
    try:
        ap_dev = trunk_sway_from_baseline(df_side)
        ap_abs = np.abs(ap_dev)
        ap_sway_mean = _nanmedian_safe(ap_abs)
        ap_sway_sd   = float(np.nanstd(ap_abs)) if np.any(np.isfinite(ap_abs)) else None
        ap_sway_peak = float(np.nanmax(ap_abs)) if np.any(np.isfinite(ap_abs)) else None
    except Exception as e:
        return ("err", dict(age=age, student=stu, error=f"ap_sway_failed: {e}"))

    # -------------------- Step events (velocity stability) --------------------
    try:
        events, nL, nR = detect_contacts_velocity_stability(
            df_side, fps,
            window=int(CONFIG["STABILITY_WINDOW"]),
            vel_thresh_norm=float(CONFIG["VEL_THRESH_NORM"]),
            min_gap_frames=int(CONFIG["MIN_EVENT_GAP_FRAMES"]),
        )
    except Exception as e:
        return ("err", dict(age=age, student=stu, error=f"detect_contacts_failed: {e}"))

    # Guard schema of events (optional but recommended)
    if events is None:
        events = []
    try:
        assert all(
            isinstance(ev, (dict, tuple, list)) or (hasattr(ev, "frame_idx") and hasattr(ev, "foot"))
            for ev in events
        ), "Invalid placement schema detected"
    except AssertionError as e:
        return ("err", dict(age=age, student=stu, error=str(e)))

    # -------------------- Step metrics (patched compute_step_metrics) --------------------
    try:
        steps = compute_step_metrics(df_side, events, cS["origin"], cS["axis"], cS["ppc"])
        df_steps = pd.DataFrame(steps) if steps else pd.DataFrame(columns=[
            "i","frame_idx","foot","step_gap_cm","nsd","understep","hgtd_cm",
            "raw_step_px","foot_len_px","ppc_used","outlier"
        ])
    except Exception as e:
        return ("err", dict(age=age, student=stu, error=f"compute_step_metrics_failed: {e}"))

    # Ensure needed columns exist
    if "understep" not in df_steps.columns:
        df_steps["understep"] = False
    if "step_gap_cm" not in df_steps.columns:
        df_steps["step_gap_cm"] = np.nan
    if "frame_idx" not in df_steps.columns:
        # If someone swapped compute_step_metrics with older one, recover best-effort
        if "i" in df_steps.columns:
            df_steps["frame_idx"] = df_steps["i"].astype(int)
        else:
            df_steps["frame_idx"] = 0

    # -------------------- robust median/mean of step gaps (cm) --------------------
    gaps = df_steps["step_gap_cm"].to_numpy(float)
    median_gap_cm = _nanmedian_safe(gaps)

    mean_gap_detected_cm = None
    try:
        valid = df_steps.loc[~df_steps["understep"].astype(bool), "step_gap_cm"].to_numpy(float)
        mean_gap_detected_cm = _mean_safe(valid)
    except Exception:
        mean_gap_detected_cm = None

    # -------------------- Front-view ML sway --------------------
    ml_sway_mean = ml_sway_sd = ml_sway_peak = None
    if isinstance(front_video, str) and os.path.exists(front_video):
        try:
            df_front, _ = run_pose_fast(
                front_video,
                frame_stride=int(CONFIG["FRAME_STRIDE"]),
                downscale=float(CONFIG["DOWNSCALE"]),
                model_complexity=int(CONFIG["MODEL_COMPLEXITY"]),
                max_frames=CONFIG.get("MAX_FRAMES", None),
                include_world=False,
            )
        except Exception:
            df_front = None

        if df_front is not None and len(df_front) >= 10:
            if "i" not in df_front.columns:
                df_front = df_front.reset_index(drop=True)
                df_front["i"] = np.arange(len(df_front), dtype=int)
            try:
                ml_dev = trunk_sway_from_baseline(df_front)
                ml_abs = np.abs(ml_dev)
                ml_sway_mean = _nanmedian_safe(ml_abs)
                ml_sway_sd   = float(np.nanstd(ml_abs)) if np.any(np.isfinite(ml_abs)) else None
                ml_sway_peak = float(np.nanmax(ml_abs)) if np.any(np.isfinite(ml_abs)) else None
            except Exception:
                ml_sway_mean = ml_sway_sd = ml_sway_peak = None

    # -------------------- Time vector for angle window --------------------
    if "t" in df_side.columns:
        tS = df_side["t"].to_numpy(float)
        # if t is all nan, fallback to i/fps
        if not np.any(np.isfinite(tS)):
            tS = df_side["i"].to_numpy(float) / float(fps)
    else:
        tS = df_side["i"].to_numpy(float) / float(fps)

    win = float(CONFIG.get("ANGLE_WINDOW_SEC", 0.25))

    # 3D availability
    use3d = all((f"xw{LM[k]}" in df_side.columns) for k in ["L_SH","R_SH","L_HP","R_HP","L_KN","R_KN","L_AN","R_AN"])

    # -------------------- Per-step angles --------------------
    per_step_rows = []
    for _, r in df_steps.iterrows():
        # SAFE: compute_step_metrics now provides frame_idx
        try:
            k1 = int(r["frame_idx"])
        except Exception:
            k1 = int(r["i"]) if "i" in r and pd.notna(r["i"]) else 0

        # clamp frame index
        if k1 < 0:
            k1 = 0
        if k1 >= len(df_side):
            k1 = len(df_side) - 1

        t0 = float(tS[k1]) if k1 < len(tS) else float(tS[-1])

        lo = int(np.searchsorted(tS, t0 - win, side="left"))
        hi = int(np.searchsorted(tS, t0 + win, side="right"))
        lo = max(0, lo)
        hi = min(len(df_side), hi)

        neck_series, trunk_series, hip_series, knee_series = [], [], [], []

        for kk in range(lo, hi):
            # trunk/neck in 2D
            sh2 = (_P2(df_side, LM["L_SH"])[kk] + _P2(df_side, LM["R_SH"])[kk]) / 2.0
            hp2 = (_P2(df_side, LM["L_HP"])[kk] + _P2(df_side, LM["R_HP"])[kk]) / 2.0
            head2 = _head_point_2d(df_side, kk)

            if np.isfinite(sh2).all() and np.isfinite(hp2).all():
                trunk_series.append(angle_to_vertical(hp2, sh2))
            else:
                trunk_series.append(np.nan)

            if head2 is not None and np.isfinite(sh2).all() and np.isfinite(hp2).all() and np.isfinite(head2).all():
                # neck as angle at shoulder midpoint: hip -> shoulder -> head
                neck_series.append(angle_3pt(hp2, sh2, head2))
            else:
                neck_series.append(np.nan)

            # hip/knee in 3D when available, else 2D fallback
            if use3d:
                def p3(idx):
                    return np.array([df_side.at[kk, f"xw{idx}"], df_side.at[kk, f"yw{idx}"], df_side.at[kk, f"zw{idx}"]], float)
                try:
                    LSH3, LHP3, LKN3, LAN3 = p3(LM["L_SH"]), p3(LM["L_HP"]), p3(LM["L_KN"]), p3(LM["L_AN"])
                    RSH3, RHP3, RKN3, RAN3 = p3(LM["R_SH"]), p3(LM["R_HP"]), p3(LM["R_KN"]), p3(LM["R_AN"])
                    hipL  = 180.0 - angle_3pt(LSH3, LHP3, LKN3)
                    hipR  = 180.0 - angle_3pt(RSH3, RHP3, RKN3)
                    kneeL = 180.0 - angle_3pt(LHP3, LKN3, LAN3)
                    kneeR = 180.0 - angle_3pt(RHP3, RKN3, RAN3)
                    hip_series.append(np.nanmean([hipL, hipR]))
                    knee_series.append(np.nanmean([kneeL, kneeR]))
                except Exception:
                    hip_series.append(np.nan); knee_series.append(np.nan)
            else:
                try:
                    LSH2 = _P2(df_side, LM["L_SH"])[kk]
                    LHP2 = _P2(df_side, LM["L_HP"])[kk]
                    LKN2 = _P2(df_side, LM["L_KN"])[kk]
                    LAN2 = _P2(df_side, LM["L_AN"])[kk]

                    RSH2 = _P2(df_side, LM["R_SH"])[kk]
                    RHP2 = _P2(df_side, LM["R_HP"])[kk]
                    RKN2 = _P2(df_side, LM["R_KN"])[kk]
                    RAN2 = _P2(df_side, LM["R_AN"])[kk]

                    hipL  = 180.0 - angle_3pt(LSH2, LHP2, LKN2)
                    hipR  = 180.0 - angle_3pt(RSH2, RHP2, RKN2)
                    kneeL = 180.0 - angle_3pt(LHP2, LKN2, LAN2)
                    kneeR = 180.0 - angle_3pt(RHP2, RKN2, RAN2)

                    hip_series.append(np.nanmean([hipL, hipR]))
                    knee_series.append(np.nanmean([kneeL, kneeR]))
                except Exception:
                    hip_series.append(np.nan); knee_series.append(np.nan)

        per_step_rows.append(dict(
            i=int(r["i"]) if ("i" in r and pd.notna(r["i"])) else None,
            frame_idx=int(k1),
            foot=r.get("foot"),
            step_gap_cm=r.get("step_gap_cm"),
            nsd=r.get("nsd"),
            hgtd_cm=r.get("hgtd_cm"),
            understep=bool(r.get("understep", False)),
            raw_step_px=r.get("raw_step_px"),
            foot_len_px=r.get("foot_len_px"),
            ppc_used=r.get("ppc_used"),
            neck_deg=_nanmedian_safe(neck_series),
            trunk_deg=_nanmedian_safe(trunk_series),
            hip_deg=_nanmedian_safe(hip_series),
            knee_deg=_nanmedian_safe(knee_series),
        ))

    dfA = pd.DataFrame(per_step_rows) if per_step_rows else pd.DataFrame(columns=[
        "i","frame_idx","foot","step_gap_cm","nsd","hgtd_cm","understep",
        "raw_step_px","foot_len_px","ppc_used","neck_deg","trunk_deg","hip_deg","knee_deg"
    ])

    # -------------------- Clip-level outputs --------------------
    n_under = int(df_steps["understep"].astype(bool).sum()) if len(df_steps) else 0

    clip_row = dict(
        age=age,
        student=stu,
        used_profile_video=profile_video,
        used_front_video=front_video,

        # sway
        ap_sway_mean_deg=ap_sway_mean,
        ap_sway_sd_deg=ap_sway_sd,
        ap_sway_peak_deg=ap_sway_peak,

        ml_sway_mean_deg=ml_sway_mean,
        ml_sway_sd_deg=ml_sway_sd,
        ml_sway_peak_deg=ml_sway_peak,

        # counts + steps
        n_L_contacts=int(nL) if nL is not None else 0,
        n_R_contacts=int(nR) if nR is not None else 0,
        n_steps_used=int(len(df_steps)),
        median_gap_cm=median_gap_cm,
        mean_gap_detected_cm=mean_gap_detected_cm,
        n_understeps=n_under,

        # angles (mean across detected steps)
        neck_mean_detected_deg=_mean_safe(dfA["neck_deg"].to_numpy(float)) if len(dfA) else None,
        trunk_mean_detected_deg=_mean_safe(dfA["trunk_deg"].to_numpy(float)) if len(dfA) else None,
        hip_mean_detected_deg=_mean_safe(dfA["hip_deg"].to_numpy(float)) if len(dfA) else None,
        knee_mean_detected_deg=_mean_safe(dfA["knee_deg"].to_numpy(float)) if len(dfA) else None,
    )

    return ("ok_tw", clip_row, df_steps, dfA)

