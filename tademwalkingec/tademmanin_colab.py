EXTS = (".mp4",".mov",".avi",".mkv",".MP4",".MOV",".AVI",".MKV")

def first_video_in(path: str) -> Optional[str]:
    vids = []
    for ext in EXTS:
        vids += glob.glob(os.path.join(path, f"*{ext}"))
    return sorted(vids)[0] if vids else None

def find_view(student_dir: str, view: str) -> Optional[str]:
    # Subfolder search (case-insensitive)
    want = "Front" if view.lower() == "front" else "Side"
    for cand in [want, want.lower(), want.upper(), want.capitalize()]:
        sub = os.path.join(student_dir, cand)
        v = first_video_in(sub) if os.path.isdir(sub) else None
        if v: return v

    # Filename pattern fallback
    patt = "*front*" if view.lower() == "front" else "*side*"
    vids = []
    for ext in EXTS:
        vids += glob.glob(os.path.join(student_dir, f"{patt}{ext}"))
    return sorted(vids)[0] if vids else None

def discover_age_dirs(root: str) -> List[Tuple[str, str]]:
    """
    Returns list of (age_tag, abs_path) for 6yrs/7yrs.
    Accepts folder names like:
      '6 years', '6 Years', '6yrs', '6YRS', '6_years', etc.
    """
    if not os.path.isdir(root):
        return []
    subs = [d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d))]
    out = []
    for d in subs:
        dn = d.lower().replace("_", " ").strip()
        if dn.startswith("6") or "6 year" in dn or "6yrs" in dn:
            out.append(("6yrs", os.path.join(root, d)))
        elif dn.startswith("7") or "7 year" in dn or "7yrs" in dn:
            out.append(("7yrs", os.path.join(root, d)))
    # stable ordering
    out = sorted(out, key=lambda x: x[0])
    return out

def build_manifest(root: str) -> pd.DataFrame:
    age_dirs = discover_age_dirs(root)
    if not age_dirs:
        raise RuntimeError(f"No age folders found under ROOT={root}. Check ROOT path and folder names.")
    man = []
    for age_tag, apath in age_dirs:
        for stu in sorted(os.listdir(apath)):
            sdir = os.path.join(apath, stu)
            if not os.path.isdir(sdir):
                continue
            fv = find_view(sdir, "front")
            sv = find_view(sdir, "side")
            if fv: man.append(dict(age=age_tag, student=stu, view="front", video=fv))
            if sv: man.append(dict(age=age_tag, student=stu, view="side",  video=sv))
    return pd.DataFrame(man)

