def process_student_pair(age_tag, student, front_video, side_video):
    front_df, fpsF = extract_jj_raw(front_video)
    side_df,  fpsS = extract_jj_raw(side_video)
    fps = fpsF if fpsF else fpsS

    met = jj_metrics_from_raw(front_df, side_df, fps=fps)

    if SAVE_PER_FRAME:
        safe = re.sub(r"[^\w\-_\. ]", "_", student).replace(" ", "_")
        front_df.to_csv(os.path.join(OUTDIR, f"{age_tag}_{safe}_FRONT_raw.csv"), index=False)
        side_df.to_csv(os.path.join(OUTDIR, f"{age_tag}_{safe}_SIDE_raw.csv"), index=False)

    if PRINT_PER_STUDENT:
        print_student_metrics(age_tag, student, front_video, side_video, met)

    return {
        "age": age_tag,
        "student": student,
        "front_video": os.path.basename(front_video),
        "side_video": os.path.basename(side_video),
        **met
    }

def main():
    pairs = []
    for age_dir in AGE_DIRS:
        age_tag = "6yrs" if age_dir.startswith("6") else "7yrs"
        age_path = os.path.join(JJ_ROOT, age_dir)
        if not os.path.isdir(age_path):
            print("Missing:", age_path)
            continue

        for student in sorted(os.listdir(age_path)):
            stu_dir = os.path.join(age_path, student)
            if not os.path.isdir(stu_dir):
                continue

            front_v = find_view_video(stu_dir, "front")
            side_v  = find_view_video(stu_dir, "side")
            if front_v and side_v:
                pairs.append(dict(age=age_tag, student=student, front=front_v, side=side_v))

    pairs = pd.DataFrame(pairs)
    print("Paired students:", len(pairs))
    if len(pairs) == 0:
        print("No paired (Front+Side) videos found. Check folder names and paths.")
        return

    rows6, rows7, errs = [], [], []

    for _, r in tqdm(pairs.iterrows(), total=len(pairs), desc="Batch students", unit="stu"):
        try:
            out = process_student_pair(r["age"], r["student"], r["front"], r["side"])
            if r["age"] == "6yrs":
                rows6.append(out)
            else:
                rows7.append(out)
        except Exception as e:
            errs.append(dict(age=r["age"], student=r["student"], error=str(e)))
            print(f"\n[ERROR] {r['age']} | {r['student']} -> {e}")

    df6 = pd.DataFrame(rows6)
    df7 = pd.DataFrame(rows7)
    dfe = pd.DataFrame(errs)

    XLS6 = os.path.join(OUTDIR, "JumpingJacks_main_6Years.xlsx")
    XLS7 = os.path.join(OUTDIR, "JumpingJacks_main_7Years.xlsx")
    XLS_ALL = os.path.join(OUTDIR, "JumpingJacks_main_All.xlsx")

    if len(df6): df6.to_excel(XLS6, index=False)
    if len(df7): df7.to_excel(XLS7, index=False)
    pd.concat([df6, df7], ignore_index=True).to_excel(XLS_ALL, index=False)

    if len(dfe):
        dfe.to_csv(os.path.join(OUTDIR, "Errors.csv"), index=False)

    print("Saved:")
    print("  6 Years:", XLS6 if len(df6) else "(none)")
    print("  7 Years:", XLS7 if len(df7) else "(none)")
    print("  All   :", XLS_ALL)
    print("  Errors:", "Errors.csv" if len(dfe) else "(none)")

if __name__ == "__main__":
    main()