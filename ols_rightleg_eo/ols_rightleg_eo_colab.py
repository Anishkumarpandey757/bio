# If you don't have a ruler/mat for OLS, leave this as None.
# When you have a known distance (e.g., 60 cm) you can set OLS_PX_PER_CM from a quick 2-click calibration.
OLS_PX_PER_CM = 3.2  # e.g.,  OLS_PX_PER_CM = 3.2  # pixels per cm

def supporting_foot_xy(df: pd.DataFrame, raised_leg="L"):
    """
    Midpoint of heel & big-toe of the supporting foot (opposite to raised_leg).
    Returns an (N,2) array in image pixel coords or None.
    """
    if raised_leg.upper() == "L":
        # stance = RIGHT foot
        if not {"x30","y30","x32","y32"}.issubset(df.columns): return None
        heel = df[["x30","y30"]].to_numpy()  # RIGHT_HEEL
        toe  = df[["x32","y32"]].to_numpy()  # RIGHT_TOE
    else:
        # stance = LEFT foot
        if not {"x29","y29","x31","y31"}.issubset(df.columns): return None
        heel = df[["x29","y29"]].to_numpy()  # LEFT_HEEL
        toe  = df[["x31","y31"]].to_numpy()  # LEFT_TOE
    return 0.5*(heel + toe)

# --- OLS stance foot drift from starting position (replaces BoS displacement) ---

# If you have a known scale, keep it; else set None and it will return px + pelvis-normalized only.
# ========= OLS Foot Drift Displacement (replaces BoS) =========
# Keep this near your other OLS config values
OLS_PX_PER_CM = 3.2   # set to None if you don't have a scale (then only *_px and *_pelvis will be filled)

def _stance_ball_xy(df: pd.DataFrame, raised_leg: str = "L", alpha: float = 0.30):
    """
    Returns (N,2) array for the BALL of the supporting foot:
      ball = toe + alpha * (heel - toe)
    Supporting foot = opposite of raised_leg ('L' means stance is right).
    """
    rl = (raised_leg or "L").upper()
    if rl == "L":
        # stance = RIGHT (RIGHT_HEEL=30, RIGHT_TOE=32)
        need = {"x30","y30","x32","y32"}
        if not need.issubset(df.columns): return None
        heel = df[["x30","y30"]].to_numpy(dtype=float)
        toe  = df[["x32","y32"]].to_numpy(dtype=float)
    else:
        # stance = LEFT (LEFT_HEEL=29, LEFT_TOE=31)
        need = {"x29","y29","x31","y31"}
        if not need.issubset(df.columns): return None
        heel = df[["x29","y29"]].to_numpy(dtype=float)
        toe  = df[["x31","y31"]].to_numpy(dtype=float)
    return toe + alpha * (heel - toe)

def foot_drift_metrics(df: pd.DataFrame,
                       raised_leg: str = "L",
                       px_per_cm: float | None = OLS_PX_PER_CM):
    """
    Foot Drift Displacement metrics (stance foot):
      - Drift from starting position over time.
      - Returns dict with max/mean total drift (cm), lateral/AP components,
        and pelvis-normalized values (dimensionless).

    Output keys:
      drift_max_cm, drift_mean_cm, drift_max_px, drift_mean_px,
      drift_lat_max_cm, drift_lat_mean_cm, drift_ap_max_cm, drift_ap_mean_cm,
      drift_pelvis_max, drift_pelvis_mean
    """
    ball = _stance_ball_xy(df, raised_leg=raised_leg, alpha=0.30)
    if ball is None or len(ball) == 0:
        return dict(drift_max_cm=None, drift_mean_cm=None,
                    drift_max_px=None, drift_mean_px=None,
                    drift_lat_max_cm=None, drift_lat_mean_cm=None,
                    drift_ap_max_cm=None,  drift_ap_mean_cm=None,
                    drift_pelvis_max=None, drift_pelvis_mean=None)

    # Robust starting point: median of first up-to-10 frames
    k0 = min(10, len(ball))
    start = np.nanmedian(ball[:k0], axis=0)

    # Total and component drifts (pixels)
    delta = ball - start
    drift_px      = np.linalg.norm(delta, axis=1)
    drift_lat_px  = np.abs(delta[:, 0])
    drift_ap_px   = np.abs(delta[:, 1])

    # Pelvis width for normalization
    if {"x23","y23","x24","y24"}.issubset(df.columns):
        LHP = df[["x23","y23"]].to_numpy(dtype=float)
        RHP = df[["x24","y24"]].to_numpy(dtype=float)
        pelvis_px = float(np.nanmedian(np.linalg.norm(LHP - RHP, axis=1)))
    else:
        pelvis_px = np.nan

    def _to_cm(arr_px):
        return (arr_px / px_per_cm) if (px_per_cm and px_per_cm > 0) else None

    out = dict(
        drift_max_px      = float(np.nanmax(drift_px)),
        drift_mean_px     = float(np.nanmean(drift_px)),
        drift_max_cm      = float(np.nanmax(_to_cm(drift_px)))      if _to_cm(drift_px)      is not None else None,
        drift_mean_cm     = float(np.nanmean(_to_cm(drift_px)))     if _to_cm(drift_px)     is not None else None,
        drift_lat_max_cm  = float(np.nanmax(_to_cm(drift_lat_px)))  if _to_cm(drift_lat_px) is not None else None,
        drift_lat_mean_cm = float(np.nanmean(_to_cm(drift_lat_px))) if _to_cm(drift_lat_px) is not None else None,
        drift_ap_max_cm   = float(np.nanmax(_to_cm(drift_ap_px)))   if _to_cm(drift_ap_px)  is not None else None,
        drift_ap_mean_cm  = float(np.nanmean(_to_cm(drift_ap_px)))  if _to_cm(drift_ap_px)  is not None else None,
        drift_pelvis_max  = float(np.nanmax(drift_px / pelvis_px))  if np.isfinite(pelvis_px) and pelvis_px > 0 else None,
        drift_pelvis_mean = float(np.nanmean(drift_px / pelvis_px)) if np.isfinite(pelvis_px) and pelvis_px > 0 else None,
    )
    return out


def summarize_neck(df: pd.DataFrame):
    """
    Clip-level neck angle stats (deg). Assumes per-frame 'neck_deg' exists
    (it does in your measure_ols_video).
    """
    s = pd.Series(df.get("neck_deg", np.nan), dtype=float)
    return dict(
        neck_mean_deg=float(s.mean(skipna=True)),
        neck_sd_deg=float(s.std(ddof=0, skipna=True)),
        neck_peak_deg=float(s.max(skipna=True))
    )

def count_toe_touches(df: pd.DataFrame, fps: float, norm_thr=0.03, min_frames=3, min_gap_s=0.30):
    """Count distinct near-floor episodes for the raised big toe."""
    toe = pd.Series(df["raised_toe_h"], dtype=float)
    near = toe <= norm_thr
    # gate with a small sustain
    run = 0
    touch_idxs = []
    for i, ok in enumerate(near.fillna(False).to_numpy()):
        if ok:
            run += 1
            if run == min_frames:
                touch_idxs.append(i)
        else:
            run = 0
    # refractory to avoid bounces
    if fps <= 0: fps = 30.0
    refr = int(fps * min_gap_s)
    cnt, last = 0, -10**9
    for i in touch_idxs:
        if i - last >= refr:
            cnt += 1
            last = i
    return int(cnt)

def ols_events_and_strategy(df, fps, raised_leg="L", age_tag=None,
                            ank_up=0.15, ank_down=0.05, min_contact_gap_frames=8,
                            onhip_thr=0.35, min_off_gap_frames=6):
    """
    - Foot touches (ankle): airborne↔grounded via hysteresis on normalized ankle height.
    - Toe touches: separate counter (big toe near floor).
    - Hands off hips: either wrist far from ipsilateral hip (normalized).
    - Strategy: rule-based from medians while airborne.
    """
    # ---- Ankle-based contact count (airborne→grounded transitions) ----
    ank = pd.Series(df["raised_ank_h"], dtype=float)
    up = ank > ank_up
    down = ank < ank_down
    grounded = pd.Series(False, index=ank.index)
    state = True if (len(down) and bool(down.iloc[0])) else False
    grounded.iloc[0] = state
    for i in range(1, len(ank)):
        if state:      # grounded
            if up.iloc[i]: state = False
        else:          # airborne
            if down.iloc[i]: state = True
        grounded.iloc[i] = state
    foot_touches_ankle = count_transitions(grounded.diff().fillna(0) > 0,
                                           min_gap_frames=min_contact_gap_frames)

    # ---- Toe-touch count (age-tuned threshold) ----
    toe_thr = 0.035 if age_tag=="6yrs" else 0.025  # 6-year olds wobble more
    toe_touches = count_toe_touches(df, fps, norm_thr=toe_thr,
                                    min_frames=3,
                                    min_gap_s=0.35 if age_tag=="6yrs" else 0.30)

    # ---- Hands off hips count ----
    onL = pd.Series(df["wristL_hipL_norm"], dtype=float) <= onhip_thr
    onR = pd.Series(df["wristR_hipR_norm"], dtype=float) <= onhip_thr
    both_on = (onL & onR)
    hands_off = ~both_on
    hands_off_cnt = count_transitions(hands_off, min_gap_frames=min_off_gap_frames)
    hands_off_pct = float(hands_off.mean()) if len(hands_off) else 0.0

    # ---- Strategy (medians while airborne to avoid contact artifacts) ----
    airborne = ~grounded
    def _med(series_name):
        s = df.loc[airborne, series_name] if airborne.any() else df[series_name]
        return float(pd.Series(s, dtype=float).median())

    med_trunk = _med("trunk_abs_deg")
    med_hip   = float(pd.concat([df["hip_L"], df["hip_R"]], axis=1).median().median())
    med_knee  = float(pd.concat([df["knee_L"], df["knee_R"]], axis=1).median().median())

    if foot_touches_ankle > 0 or toe_touches > 0:
        strategy = "Stepping"
    elif med_knee >= 15 and med_trunk < 10:
        strategy = "Knee strategy"
    elif med_hip >= 15 and med_trunk >= 7:
        strategy = "Hip strategy"
    else:
        strategy = "Ankle/minimal"

    return dict(
        foot_touches_ankle=int(foot_touches_ankle),
        toe_touches=int(toe_touches),
        hands_off_cnt=int(hands_off_cnt),
        hands_off_pct=hands_off_pct,
        strategy=strategy,
        med_trunk_deg=med_trunk,
        med_hip_deg=med_hip,
        med_knee_deg=med_knee
    )

def summarize_ols_clip(df, fps, view):
    sway_abs = pd.Series(df["trunk_abs_deg"], dtype=float)
    mean_deg = float(sway_abs.mean())
    sd_deg   = float(sway_abs.std(ddof=0))
    peak_deg = float(sway_abs.max())
    best_idx = int(sway_abs.idxmax()) if len(sway_abs) else 0
    duration = float(len(df) / (fps if fps else 30.0))
    return dict(view=view, sway_mean_deg=mean_deg, sway_sd_deg=sd_deg,
                sway_peak_deg=peak_deg, best_idx=best_idx, clip_dur_s=duration)

def export_ols_overlay(video_path, df, summ, out_png):
    cap = cv2.VideoCapture(video_path)
    fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
    idx = summ["best_idx"]
    cap.set(cv2.CAP_PROP_POS_FRAMES, idx)
    ok, frame = cap.read()
    cap.release()
    if not ok: return
    H, W = frame.shape[:2]
    sh = (int(df.loc[idx,"sh_x"]), int(df.loc[idx,"sh_y"]))
    hp = (int(df.loc[idx,"hp_x"]), int(df.loc[idx,"hp_y"]))

    # header
    ov = frame.copy()
    cv2.rectangle(ov, (10,10), (W-10, 160), (0,0,0), -1)
    frame = cv2.addWeighted(ov, 0.35, frame, 0.65, 0)

    # vertical midline through hip
    cv2.line(frame, (hp[0], 0), (hp[0], H), (0,255,255), 2)
    # trunk vector
    cv2.arrowedLine(frame, hp, sh, (0,255,0), 3, tipLength=0.06)

    def put(y, txt): cv2.putText(frame, txt, (20,y), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255,255,255), 2, cv2.LINE_AA)
    put(40, f"{summ['view'].title()} sway: mean {summ['sway_mean_deg']:.1f}°, peak {summ['sway_peak_deg']:.1f}°")
    put(65, f"Strategy: {summ['strategy']}")
    put(90, f"Foot (ankle) touches: {summ['foot_touches_ankle']}  |  Toe touches: {summ['toe_touches']}")
    put(115,f"Hands-off count: {summ['hands_off_cnt']}  ({summ['hands_off_pct']*100:.0f}%)")

    cv2.imwrite(out_png, frame)

