def angle_3pt(A,B,C, eps=1e-8):
    BA, BC = A-B, C-B
    na, nc = np.linalg.norm(BA), np.linalg.norm(BC)
    if na < eps or nc < eps: return np.nan
    cosv = np.dot(BA,BC) / (na*nc)
    return float(np.degrees(np.arccos(np.clip(cosv, -1.0, 1.0))))

def angle_to_vertical(P0, P1):
    v = (P1 - P0).astype(float)
    n = np.linalg.norm(v)
    if n < 1e-8: return np.nan
    v /= n
    return float(np.degrees(np.arccos(np.clip(np.dot(v, np.array([0.0,-1.0])), -1, 1))))

def angle_signed_to_vertical(P0, P1):
    """Signed trunk angle (deg) vs vertical; + = lean to image +x (right), - = to -x (left)."""
    v = (P1 - P0).astype(float)
    n = np.linalg.norm(v)
    if n < 1e-8: return np.nan
    v /= n
    unsigned = np.degrees(np.arccos(np.clip(np.dot(v, np.array([0.0,-1.0])), -1, 1)))
    sgn = 1.0 if v[0] >= 0 else -1.0
    return float(sgn * unsigned)

def pelvis_width_xy(P2):
    d = np.linalg.norm(P2[LM['L_HP']] - P2[LM['R_HP']])
    return float(d) if d > 1e-8 else np.nan

def estimate_floor_y(P2, H=None):
    # ankles + (if present) heels/toes (more robust to partial occlusion)
    ys = [P2[LM['L_AN'],1], P2[LM['R_AN'],1]]
    if P2.shape[0] >= 33:
        ys += [P2[29,1], P2[30,1], P2[31,1], P2[32,1]]
    y = np.array(ys, dtype=float)
    y = y[np.isfinite(y)]
    if y.size == 0:
        return float(H*0.98) if H is not None else np.nan
    return float(np.percentile(y, 95))  # near-floor robust estimate

def rolling_med(x, k=5):
    return pd.Series(x, dtype=float).rolling(k, center=True, min_periods=1).median().to_numpy()

def count_transitions(boolean_series, min_gap_frames=6):
    """Count rising edges True with simple debounce."""
    b = pd.Series(boolean_series, dtype=bool).fillna(False).to_numpy()
    cnt = 0
    cool = 0
    for i in range(1, len(b)):
        if cool > 0:
            cool -= 1
            continue
        if (not b[i-1]) and b[i]:
            cnt += 1
            cool = min_gap_frames
    return int(cnt)
def angle_between_vecs(v1, v2, eps=1e-8):
    n1, n2 = np.linalg.norm(v1), np.linalg.norm(v2)
    if n1 < eps or n2 < eps: return np.nan
    c = np.dot(v1, v2) / (n1*n2)
    return float(np.degrees(np.arccos(np.clip(c, -1.0, 1.0))))

def neck_goniometer_deg(P3, LM):
    """
    Goniometer-like cervical angle = angle between:
      - trunk vector: shoulder_mid - hip_mid
      - head/neck vector: ear_mid - shoulder_mid
    Uses 3D coords to be view-agnostic.
    """
    sh3 = (P3[LM['L_SH']] + P3[LM['R_SH']]) / 2.0
    hp3 = (P3[LM['L_HP']] + P3[LM['R_HP']]) / 2.0
    ear3 = (P3[LM['L_EAR']] + P3[LM['R_EAR']]) / 2.0
    trunk = sh3 - hp3
    head  = ear3 - sh3
    return angle_between_vecs(trunk, head)

def measure_ols_video(video_path, view="front", raised_leg="L", smooth_k=5, model_complexity=1):
    """
    view: 'front' or 'side'
    raised_leg: 'L' for left-leg raised (this dataset), 'R' otherwise
    """
    cap = cv2.VideoCapture(video_path)
    fps = cap.get(cv2.CAP_PROP_FPS)
    if not fps or not (10 < fps < 120): fps = 30.0

    rows = []
    with mp_pose.Pose(model_complexity=model_complexity,
                      min_detection_confidence=0.6,
                      min_tracking_confidence=0.6) as pose:
        while True:
            ok, frame = cap.read()
            if not ok: break
            H, W = frame.shape[:2]
            res = pose.process(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))

            if not res.pose_landmarks:
                rows.append([np.nan]*20); continue

            P2 = np.array([[lm.x*W, lm.y*H] for lm in res.pose_landmarks.landmark], dtype=float)
            if res.pose_world_landmarks:
                P3 = np.array([[lm.x, lm.y, lm.z] for lm in res.pose_world_landmarks.landmark], dtype=float)
            else:
                P3 = np.concatenate([P2, np.zeros((P2.shape[0],1))], axis=1)

            # key centers
            sh2 = (P2[LM['L_SH']] + P2[LM['R_SH']]) / 2.0
            hp2 = (P2[LM['L_HP']] + P2[LM['R_HP']]) / 2.0

            # Sway: signed angle hip->shoulder vs vertical
            trunk_signed = angle_signed_to_vertical(hp2, sh2)  # deg (+ right, - left)
            trunk_abs = abs(trunk_signed)

            # 3D angles for strategy:
            neck_deg = angle_3pt(P3[LM['L_HP']], (P3[LM['L_SH']]+P3[LM['R_SH']])/2.0, (P3[LM['L_EAR']]+P3[LM['R_EAR']])/2.0)
            hip_R  = 180.0 - angle_3pt(P3[LM['R_SH']], P3[LM['R_HP']], P3[LM['R_KN']])
            hip_L  = 180.0 - angle_3pt(P3[LM['L_SH']], P3[LM['L_HP']], P3[LM['L_KN']])
            knee_R = 180.0 - angle_3pt(P3[LM['R_HP']], P3[LM['R_KN']], P3[LM['R_AN']])
            knee_L = 180.0 - angle_3pt(P3[LM['L_HP']], P3[LM['L_KN']], P3[LM['L_AN']])

            # floor & scale
            y_floor = estimate_floor_y(P2, H=H)
            px_scale = pelvis_width_xy(P2) or np.nan

            # choose raised ankle
            ankL_y = float(P2[LM['L_AN'],1]); ankR_y = float(P2[LM['R_AN'],1])
            raised_y = ankL_y if raised_leg.upper()=="L" else ankR_y
            raised_h = (y_floor - raised_y) / px_scale if np.isfinite(px_scale) else np.nan
            raised_h = max(raised_h, 0.0) if np.isfinite(raised_h) else np.nan

            # wrist-hip distances (normalized)
            d_L = np.linalg.norm(P2[LM['L_WR']] - P2[LM['L_HP']]) / (px_scale if np.isfinite(px_scale) else np.nan)
            d_R = np.linalg.norm(P2[LM['R_WR']] - P2[LM['R_HP']]) / (px_scale if np.isfinite(px_scale) else np.nan)

            rows.append([
                trunk_signed, trunk_abs, neck_deg,
                hip_R, hip_L, knee_R, knee_L,
                raised_h, d_L, d_R, y_floor, px_scale,
                sh2[0], sh2[1], hp2[0], hp2[1]   # for overlay
            ])

    cap.release()
    cols = ["trunk_signed_deg","trunk_abs_deg","neck_deg",
            "hip_R","hip_L","knee_R","knee_L",
            "raised_h_norm","wristL_hipL_norm","wristR_hipR_norm",
            "y_floor","pelvis_px","sh_x","sh_y","hp_x","hp_y"]
    df = pd.DataFrame(rows, columns=cols)

    # Smooth key kinematic series
    for k in ["trunk_signed_deg","trunk_abs_deg","neck_deg","hip_R","hip_L","knee_R","raised_h_norm",
              "wristL_hipL_norm","wristR_hipR_norm"]:
        df[k] = pd.Series(df[k]).rolling(smooth_k, center=True, min_periods=1).median()

    return df, float(fps)


